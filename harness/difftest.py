"""Differential test: vulture 2.16 versus condor.

For every project in corpus.toml and every flag set it lists, both tools run
from the project's root with the same arguments. condor deliberately differs
from vulture (spec/improvements.md), so the report lists, per run, the
findings only vulture reports and the findings only condor reports, with
samples, for review. Exit codes are compared too. The results are written to harness/REPORT.md and
harness/results.json.

Usage (from the repository root, after `cargo build --release`):

    uv run --python 3.14 python harness/difftest.py [--only NAME ...] [--jobs N]

vulture runs as `uvx --python 3.14 --from vulture==2.16 vulture`.
"""

import argparse
import concurrent.futures
import json
import os
import shutil
import subprocess
import sys
import sysconfig
import time
import tomllib
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
CACHE = ROOT / "target" / "corpus"
CONDOR = ROOT / "target" / "release" / "condor"
VULTURE = ["uvx", "-q", "--python", "3.14", "--from", "vulture==2.16", "vulture"]

def run(cmd, cwd, timeout=3600):
    start = time.perf_counter()
    proc = subprocess.run(cmd, cwd=cwd, capture_output=True, timeout=timeout)
    return proc.returncode, proc.stdout, proc.stderr, time.perf_counter() - start


def checkout(project):
    if "local" in project:
        return local_input(project["local"])
    dest = CACHE / project["name"]
    if not dest.exists():
        CACHE.mkdir(parents=True, exist_ok=True)
        subprocess.run(
            ["git", "clone", "-q", "--depth", "1", "--branch", project["tag"], project["repo"], str(dest)],
            check=True,
        )
    commit = subprocess.run(
        ["git", "rev-parse", "HEAD"], cwd=dest, capture_output=True, text=True, check=True
    ).stdout.strip()
    return dest, commit


def local_input(name):
    if name == "python3.14-stdlib":
        return Path(sysconfig.get_paths()["stdlib"]), f"CPython {sys.version.split()[0]}"
    if name == "edge-cases":
        dest = CACHE / "edge-cases"
        if dest.exists():
            shutil.rmtree(dest)
        subprocess.run([sys.executable, str(HERE / "edge_cases.py"), str(dest)], check=True)
        return dest, "generated by harness/edge_cases.py"
    raise ValueError(name)


def compare(project, flag_set, flags, cwd):
    paths = project.get("paths", ["."])
    if project.get("local") == "python3.14-stdlib":
        flags = [*flags, "--exclude", "site-packages"]
    args = [*flags, *paths]
    v_code, v_out, v_err, v_time = run([*VULTURE, *args], cwd)
    c_code, c_out, c_err, c_time = run([str(CONDOR), *args], cwd)
    v_err_n = v_err.decode("utf-8", "replace")
    c_err_n = c_err.decode("utf-8", "replace")
    result = {
        "project": project["name"],
        "flags": flag_set,
        "args": args,
        "vulture_exit": v_code,
        "condor_exit": c_code,
        "stdout_lines": v_out.count(b"\n"),
        "stdout_equal": v_out == c_out,
        "stderr_equal": v_err_n == c_err_n,
        "exit_equal": v_code == c_code,
        "vulture_seconds": round(v_time, 3),
        "condor_seconds": round(c_time, 3),
    }
    v_lines, c_lines = set(v_out.splitlines()), set(c_out.splitlines())
    only_v = [l.decode("utf-8", "replace") for l in sorted(v_lines - c_lines)]
    only_c = [l.decode("utf-8", "replace") for l in sorted(c_lines - v_lines)]
    result["condor_lines"] = c_out.count(b"\n")
    result["only_vulture_count"] = len(only_v)
    result["only_condor_count"] = len(only_c)
    result["only_vulture"] = only_v[:300]
    result["only_condor"] = only_c[:300]
    if not result["stderr_equal"]:
        v_lines, c_lines = set(v_err_n.splitlines()), set(c_err_n.splitlines())
        result["stderr_only_vulture"] = sorted(v_lines - c_lines)[:20]
        result["stderr_only_condor"] = sorted(c_lines - v_lines)[:20]
    result["equal"] = result["stdout_equal"] and result["exit_equal"]
    return result


def write_report(results, projects, path):
    lines = [
        "# Differential test report",
        "",
        "vulture 2.16 on CPython 3.14 versus condor, run by `harness/difftest.py` on the",
        "corpus in `harness/corpus.toml`. condor deliberately differs from vulture",
        "(spec/improvements.md): \"only vulture\" counts findings condor no longer",
        "reports, \"only condor\" counts new ones. Exit codes are compared.",
        "",
        f"Runs: {len(results)}. Runs with identical findings: {sum(r['stdout_equal'] for r in results)}. "
        f"Runs with different exit codes: {sum(not r['exit_equal'] for r in results)}.",
        "",
        "| Project | Kind | Revision | Flags | vulture | condor | Only vulture | Only condor | Exit | vulture (s) | condor (s) |",
        "|---|---|---|---|---:|---:|---:|---:|---|---:|---:|",
    ]
    for r in results:
        p = projects[r["project"]]
        exit_col = f"{r['vulture_exit']}" if r["exit_equal"] else f"**{r['vulture_exit']} vs {r['condor_exit']}**"
        lines.append(
            f"| {r['project']} | {p['kind']} | {p['revision'][:12]} | {r['flags']} | {r['stdout_lines']} | "
            f"{r['condor_lines']} | {r['only_vulture_count']} | {r['only_condor_count']} | {exit_col} | "
            f"{r['vulture_seconds']} | {r['condor_seconds']} |"
        )
    lines += ["", "## Samples of differences (default flags)", ""]
    for r in results:
        if r["flags"] != "default" or r["stdout_equal"]:
            continue
        lines.append(f"### {r['project']}")
        lines.append("")
        for key, title in (("only_vulture", "Only vulture"), ("only_condor", "Only condor")):
            if r[key]:
                lines.append(f"{title} ({r[key + '_count']}, first 10):")
                lines.append("```")
                lines.extend(r[key][:10])
                lines.append("```")
        lines.append("")
    path.write_text("\n".join(lines) + "\n")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--only", nargs="*", help="project names to run")
    parser.add_argument("--jobs", type=int, default=4)
    parser.add_argument("--report", default=str(HERE / "REPORT.md"))
    parser.add_argument("--baseline", help="JSON file of the expected differences; fail if they change")
    parser.add_argument("--update-baseline", action="store_true", help="write the differences to --baseline")
    args = parser.parse_args()

    corpus = tomllib.loads((HERE / "corpus.toml").read_text())
    flag_sets = corpus["flag_sets"]
    projects = [p for p in corpus["project"] if not args.only or p["name"] in args.only]
    if not CONDOR.exists():
        sys.exit(f"{CONDOR} not found: run `cargo build --release` first")

    jobs = []
    by_name = {}
    for project in projects:
        cwd, revision = checkout(project)
        by_name[project["name"]] = {**project, "revision": revision}
        for flag_set in project["flags"]:
            jobs.append((project, flag_set, flag_sets[flag_set], cwd))

    results = []
    with concurrent.futures.ThreadPoolExecutor(args.jobs) as pool:
        futures = [pool.submit(compare, *job) for job in jobs]
        for job, fut in zip(jobs, futures):
            r = fut.result()
            results.append(r)
            print(f"{r['project']:28} {r['flags']:15} vulture={r['stdout_lines']:5} condor={r['condor_lines']:5} "
                  f"-{r['only_vulture_count']} +{r['only_condor_count']} exit={r['vulture_exit']}/{r['condor_exit']} "
                  f"time={r['vulture_seconds']}s/{r['condor_seconds']}s", flush=True)

    write_report(results, by_name, Path(args.report))
    if args.report == str(HERE / "REPORT.md"):
        # The tracked results go with the tracked report only.
        (HERE / "results.json").write_text(json.dumps(results, indent=1) + "\n")
        subprocess.run([sys.executable, str(HERE / "summarize.py")], check=True)
    exit_diffs = sum(not r["exit_equal"] for r in results)
    print(f"{len(results)} runs, {exit_diffs} with different exit codes")
    failed = exit_diffs > 0
    if args.baseline:
        # Findings differences are expected (improvements); unexpected ones
        # are regressions or new behaviour to review.
        current = {
            f"{r['project']} {r['flags']}": {"only_vulture": r["only_vulture"], "only_condor": r["only_condor"]}
            for r in results
        }
        path = Path(args.baseline)
        if args.update_baseline:
            path.write_text(json.dumps(current, indent=1, sort_keys=True) + "\n")
            print(f"wrote {path}")
        else:
            expected = json.loads(path.read_text())
            changed = sorted(k for k in current.keys() | expected.keys() if current.get(k) != expected.get(k))
            for key in changed:
                print(f"findings differ from {path} for {key}:")
                for side in ("only_vulture", "only_condor"):
                    now, then = set(current.get(key, {}).get(side, [])), set(expected.get(key, {}).get(side, []))
                    for line in sorted(now - then):
                        print(f"  new {side}: {line}")
                    for line in sorted(then - now):
                        print(f"  gone {side}: {line}")
            failed |= bool(changed)
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
